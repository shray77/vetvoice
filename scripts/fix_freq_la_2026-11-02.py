#!/usr/bin/env python3
"""Task 225: чистка freq-la-конфликтов по российским инструкциям (истина = RU-лейбл).

Приказ владельца 2026-11-02: «бля, лучше чинить» — 63 WARN'а валидатора
(общая frequency «N раз в день/сутки» против повидовой «однократно»/«≥36 ч»)
чинятся по реальным RU-инструкциям, семейство за семейством. Приложение
берёт повидовую частоту (data_load_service.dart), так что главное поле
беды — общая frequency (голосовой сценарий/до выбора вида) + мусорные
повидовые ветки, противоречащие лейблам.

ИСТОЧНИКИ (проверены 2026-11-02):
- Амоксициллин 15% (150 мг/мл), моно-суспензии: biohimfarm.ru «однократно
  в/м или п/к… при необходимости повторно через 48 часов» (все виды:
  КРС, лошади, МРС, свиньи, собаки, кошки); bzvsp.by (INVESA «Амоксициллин
  15% ЛА»): «однократно… повторное введение через 48 часов» (все виды).
  → 15 записей: общая и ВСЕ повидовые ветки = лейбл-формулировка.
- Амоксигард 150 (амоксициллин+клавулановая): webvet.ru «вводят 1 раз в
  сутки, курс 3-5 дней» → все ветки и общая.
- Нороклав инъекционный 140: vetклиники/gomeovet «п/к 1 мл/20 кг, курс
  3-5 суток» (КРС, собаки; кошки — 12,5 мг/кг курсом, petsik) → «1 раз в
  сутки, 3-5 дней» для КРС/собак/кошек; МРС/свиньи/лошади вне лейбла —
  их ветки не трогаем (долг «виды вне лейбла»).
- Гентамокс 150 (амоксициллин+гентамицин): tandem-industry «в/м 1 мл/10 кг
  1 раз в день в течение 3 дней» → все ветки и общая.
- Синулокс LC (интрамаммарный, только дойные коровы): webvet «3 шприца на
  поражённую четверть, по одному с интервалом 12 часов» → частота КРС по
  лейблу; мусорные ветки собак/кошек/МРС/свиней/лошадей (маститный
  препарат с дозами 15-20 мг/кг для собак!) удалены, animals=['КРС'].
- Флорфеникол 30% (300 мг/мл, инъекции): gzvp.by (Гомельский з-д): «КРС:
  в/м 1 мл/15 кг дважды с интервалом 48 ч; п/к 2 мл/15 кг однократно;
  свиньи: в/м 1 мл/20 кг дважды с интервалом 48 ч; птицы в показаниях
  НЕТ»; vetlek (Флорикол): «свиньям… двукратно с интервалом 48 часов».
  → КРС/свиньи = лейбл; птица/кошки — вне лейбла, ветки остаются (долг).
- Тилмипул (тилмикозин 25% оральный): vetклиники «телятам 0,5 мл/10 кг
  ДВАЖДЫ В СУТКИ 3-5 дней; свиньям 0,8% раствор ЕЖЕДНЕВНО 3 дня (замена
  питья); птице 0,3% раствор ЕЖЕДНЕВНО 3 суток» → ветки и общая по лейблу
  (единственный тилмикозин, чей лейбл НЕ «свиньям однократно»).
- Тилмовет (тилмикозин 25%): tsenovik «телятам 12,5 мг/кг 3-5 суток» →
  телята/птица ежедневно; ветки свиней «однократно» из исходных лейблов
  не трогаем, общая = видовой summary («свиньям — однократно; телятам и
  птице — ежедневно, 3-5 дней»). Summary-подход не выдумывает данных:
  раскладывает общее поле по видам, устраняя ложное «единого режима нет».
- Фенбендазолы (ФЕБТАЛ/Панакур/Фенбенгран/Пигфен/гельмистоп): ФЕБТАЛ:
  «взрослым однократно; щенкам и котятам — 1 раз в день 3 дня подряд»
  (vetapteka1/vetlek/4lapy) → ветки уже лейбл-верны, общая = «однократно;
  собакам и кошкам — 3 дня подряд».
- Пиро-Стоп (имидокарб 120): полный лейбл vetapteka-litarova: КРС/лошади/
  овцы/собаки «однократно» (повторы — только схемы носительства) →
  Лошади «1 раз в сутки» = мусор → «однократно»; общая «однократно».
- Ивермек (ивермектин 10): zooman/dogcitypet «свиньям 1 мл/33 кг
  однократно», «Ивермек вводят однократно» → Свиньи «1 раз в день» =
  мусор → «однократно»; общая «однократно».
- Эквисект паста (аверсектин): emall/zoovetsnab/НБЦ Фармбиомед PDF
  «лошадям ОДНОКРАТНО перорально 2 г/100 кг» → запись несла мусорные
  ветки КРС «1 раз в сутки 20 мг/кг» (!) и собак/кошек: animals=['Лошади'],
  ветка Лошадей «однократно», общая «однократно».
- СЕКС БАРЬЕР (мепрегенолацетат+этинилэстрадиол): astrapharm «дают при
  наступлении полового возбуждения… до полного прекращения половой охоты»
  (суточная доза по весу) → общая и ветка кошек = «в период половой охоты,
  до её прекращения»; сукам частота теперь доезжает через общую.
- Селенат LA (селенат бария, депо): ветки «однократно» согласованы →
  общая «однократно».
- Виме-Лайт IV: 2 из 3 веток «по показаниям» → общая «по показаниям».
- Робенакоксибы (Робексера/Робенекс/Оноксеб): собаки «1 раз в день»,
  кошки «однократно» — оба режима в классе лейблов → общая = summary
  «собакам — ежедневно; кошкам — однократно» (ветки не тронуты).
- Галастоп/Универм/Инспектор ушные/Тилмакс: лейблы не верифицированы —
  общая = ЧЕСТНЫЙ SUMMARY собственных повидовых веток (без выдумки).
- НЕ ЧИНЯТСЯ (осознанный долг, WARN остаётся): Неомастин #154 и
  Максиклавир #166 — интрамаммарные противомаститные записи с ветками
  собак/кошек; требуют полной лейбл-ревизии записи, а не частотного фикса.
- Бонус: Тилмикозин ВЛ 25 #913 — мусорная concentration 25000 мг/мл
  (=25000% ?!) при форме 25% → 250 мг/мл (25% водного раствора).

Идемпотентен: повторный запуск — no-op (exit 0). --check — только отчёт.

АКТУАЛИЗАЦИЯ 2026-11-10 (Task 228, аудит старого): ожидания двух секций
синхронизированы с более поздними волнами, данные НЕ тронуты:
- Синулокс LC #1731: Task 226 перевёл лактационные шприцы на семейную норму
  «N введений с интервалом 12-24 ч» — текущая «трёхкратно с интервалом 12
  часов» семантически равна лейблу webvet (3 шприца × 12 ч); ожидание
  скрипта обновлено с вербатим-формы на семейную, чтобы повторный прогон
  не откатывал решение Task 226.
- Тилмакс #37: Task 227 срезал кошек (Видаль: «применяют свиньям с лечебной
  целью», animals=['Свиньи']) и поставил частоту «однократно»; старое
  ожидание «свиньям — однократно; кошкам — ежедневно» противоречило бы
  срезанному виду — актуализировано на «однократно».
Формат: indent=2, ensure_ascii=False, завершающий \n (round-trip байт-в-байт).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DB = REPO / "assets" / "data" / "drugs_calc.json"

AMOX = "однократно, при необходимости повторно через 48 часов"
AMOX_MONO = {132, 681, 817, 896, 926, 1121, 1400, 1515, 1585, 1717,
             1751, 1964, 2068, 2087, 2143, 2191}
DAILY_3_5 = "1 раз в сутки, 3-5 дней"
DAILY_3 = "1 раз в день, 3 дня"
FLOR_KRS = "однократно (п/к) или двукратно с интервалом 48 часов (в/м)"
FLOR_PIG = "двукратно с интервалом 48 часов"
FLOR_COMMON = ("КРС — однократно (п/к) или дважды с интервалом 48 ч (в/м); "
               "свиньям — дважды с интервалом 48 ч")
FLOR_INJ = {433, 538, 563, 894, 925, 1033, 1118, 1915, 2034, 2123, 2281}
TILM_COMMON = "свиньям — однократно; телятам и птице — ежедневно, 3-5 дней"
TILM = {392, 912, 913, 936, 1352, 1389, 1497, 1530, 1894, 2100}
FENB_COMMON = "однократно; собакам и кошкам — 3 дня подряд"
FENB = {1649, 1668, 1767, 1780, 2105}
ROBE_COMMON = "собакам — ежедневно; кошкам — однократно"
ROBE = {20, 86, 112}


def set_branch_freq(rec: dict, animal: str, value: str) -> bool:
    br = (rec.get("animal_specific") or {}).get(animal)
    if not isinstance(br, dict):
        return False
    if br.get("frequency") == value:
        return False
    br["frequency"] = value
    return True


def set_common(rec: dict, value: str) -> bool:
    if rec.get("frequency") == value:
        return False
    rec["frequency"] = value
    return True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    db = json.loads(DB.read_text(encoding="utf-8"))
    by_id = {d.get("id"): d for d in db["drugs_calc"]}
    changes: list[str] = []

    # ── 1. Амоксициллин 150 моно (LA и обычные): лейбл на все ветки ──
    for rid in sorted(AMOX_MONO):
        rec = by_id[rid]
        if set_common(rec, AMOX):
            changes.append(f"#{rid} {rec['name']}: общая частота → лейбл")
        for animal in list((rec.get("animal_specific") or {})):
            if set_branch_freq(rec, animal, AMOX):
                changes.append(f"#{rid} {rec['name']}: {animal} → лейбл")

    # ── 2. Комбо-пенициллины: суточный курс по лейблам ──
    for rid, val in ((1548, DAILY_3_5), (2380, DAILY_3)):
        rec = by_id[rid]
        if set_common(rec, val):
            changes.append(f"#{rid} {rec['name']}: общая → «{val}»")
        for animal in list((rec.get("animal_specific") or {})):
            if set_branch_freq(rec, animal, val):
                changes.append(f"#{rid} {rec['name']}: {animal} → «{val}»")
    rec = by_id[2041]  # Нороклав: по лейблу КРС/собаки/кошки
    if set_common(rec, DAILY_3_5):
        changes.append(f"#2041 Нороклав: общая → «{DAILY_3_5}»")
    for animal in ("КРС", "Собаки", "Кошки"):
        if set_branch_freq(rec, animal, DAILY_3_5):
            changes.append(f"#2041 Нороклав: {animal} → «{DAILY_3_5}»")

    # ── 3. Синулокс LC: интрамаммарный, только КРС, 3 введения × 12 ч ──
    # (актуализировано 2026-11-10: Task 226 нормализовал лактационные шприцы
    # к семейной форме «N введений × 12 ч»; семантика лейбла webvet сохранена)
    rec = by_id[1731]
    synulox = "трёхкратно с интервалом 12 часов"
    spec = rec.get("animal_specific") or {}
    junk = [a for a in spec if a != "КРС"]
    if junk:
        for a in junk:
            spec.pop(a)
        rec["animals"] = ["КРС"]
        changes.append(f"#1731 Синулокс LC: удалены вне-лейбловые ветки {junk}, animals=['КРС']")
    if set_branch_freq(rec, "КРС", synulox):
        changes.append("#1731 Синулокс LC: КРС → «трёхкратно с интервалом 12 ч (Task 226)»")
    if set_common(rec, synulox):
        changes.append("#1731 Синулокс LC: общая → семейная форма Task 226")

    # ── 4. Флорфениколы 300/400 инъекционные ──
    for rid in sorted(FLOR_INJ):
        rec = by_id[rid]
        if set_branch_freq(rec, "КРС", FLOR_KRS):
            changes.append(f"#{rid} {rec['name']}: КРС → «{FLOR_KRS}»")
        if set_branch_freq(rec, "Свиньи", FLOR_PIG):
            changes.append(f"#{rid} {rec['name']}: Свиньи → «{FLOR_PIG}»")
        if set_common(rec, FLOR_COMMON):
            changes.append(f"#{rid} {rec['name']}: общая → видовой лейбл-сводкой")
    # Флорокс OR #203 (оральный, лейбл не верифицирован): честный summary веток
    rec = by_id[203]
    if set_common(rec, "КРС — 1 раз в 48 часов; свиньям — дважды с интервалом 48 ч; птице — ежедневно"):
        changes.append("#203 Флорокс OR: общая → видовой сводкой веток")

    # ── 5. Тилмикозины ──
    rec = by_id[1082]  # Тилмипул — единственный с полным лейблом
    if set_branch_freq(rec, "КРС", "2 раза в сутки, 3-5 дней"):
        changes.append("#1082 Тилмипул: КРС → «2 раза в сутки, 3-5 дней»")
    if set_branch_freq(rec, "Свиньи", "ежедневно в течение 3 дней (с питьевой водой)"):
        changes.append("#1082 Тилмипул: Свиньи → «ежедневно 3 дня»")
    if set_branch_freq(rec, "Птица", "ежедневно в течение 3 дней"):
        changes.append("#1082 Тилмипул: Птица → «ежедневно 3 дня»")
    if set_common(rec, "телятам — 2 раза в сутки, 3-5 дней; свиньям и птице — ежедневно, 3 дня"):
        changes.append("#1082 Тилмипул: общая → лейбл")
    for rid in sorted(TILM):
        rec = by_id[rid]
        if set_common(rec, TILM_COMMON):
            changes.append(f"#{rid} {rec['name']}: общая → видовой сводкой (ветки не тронуты)")
    # (актуализировано 2026-11-10: Task 227 срезал кошек — animals=['Свиньи'],
    # частота «однократно» по Видали; сводка «кошкам — ежедневно» отменена)
    if set_common(by_id[37], "однократно"):
        changes.append("#37 Тилмакс: общая → «однократно» (Task 227)")

    # ── 6. Фенбендазолы ──
    for rid in sorted(FENB):
        if set_common(by_id[rid], FENB_COMMON):
            changes.append(f"#{rid} {by_id[rid]['name']}: общая → «{FENB_COMMON}»")

    # ── 7. Робенакоксибы ──
    for rid in sorted(ROBE):
        if set_common(by_id[rid], ROBE_COMMON):
            changes.append(f"#{rid} {by_id[rid]['name']}: общая → «{ROBE_COMMON}»")

    # ── 8. Одиночные по лейблам ──
    rec = by_id[1350]  # Пиро-Стоп
    if set_branch_freq(rec, "Лошади", "однократно"):
        changes.append("#1350 Пиро-Стоп: Лошади «1 раз в сутки» → «однократно» (лейбл)")
    if set_common(rec, "однократно"):
        changes.append("#1350 Пиро-Стоп: общая → «однократно»")
    rec = by_id[1692]  # Ивермек
    if set_branch_freq(rec, "Свиньи", "однократно"):
        changes.append("#1692 Ивермек: Свиньи «1 раз в день» → «однократно» (лейбл)")
    if set_common(rec, "однократно"):
        changes.append("#1692 Ивермек: общая → «однократно»")
    rec = by_id[1994]  # Эквисект паста — только лошади
    spec = rec.get("animal_specific") or {}
    junk = [a for a in spec if a != "Лошади"]
    if junk:
        for a in junk:
            spec.pop(a)
        rec["animals"] = ["Лошади"]
        changes.append(f"#1994 Эквисект паста: удалены вне-лейбловые ветки {junk}, animals=['Лошади']")
    if set_branch_freq(rec, "Лошади", "однократно"):
        changes.append("#1994 Эквисект паста: Лошади → «однократно»")
    if set_common(rec, "однократно"):
        changes.append("#1994 Эквисект паста: общая → «однократно»")
    if set_common(by_id[1926], "однократно"):
        changes.append("#1926 Селенат LA: общая → «однократно»")
    rec = by_id[1031]  # СЕКС БАРЬЕР
    label = "в период половой охоты, до её прекращения"
    if set_branch_freq(rec, "Кошки", label):
        changes.append(f"#1031 СЕКС БАРЬЕР: Кошки → «{label}»")
    if set_common(rec, label):
        changes.append(f"#1031 СЕКС БАРЬЕР: общая → «{label}» (сукам доезжает через общую)")
    if set_common(by_id[277], "по показаниям"):
        changes.append("#277 Виме-Лайт IV: общая → «по показаниям»")
    if set_common(by_id[2367], "собакам — однократно; кошкам — 1 раз в 24 часа"):
        changes.append("#2367 Галастоп: общая → видовой сводкой веток")
    if set_common(by_id[2036], "птице, кроликам и пушным зверям — однократно"):
        changes.append("#2036 Универм: общая → сводкой веток")
    if set_common(by_id[1423], "КРС и МРС — однократно; собакам — каждые 24 ч; кошкам — 1 раз в месяц"):
        changes.append("#1423 Инспектор ушные капли: общая → сводкой веток")

    # ── 9. Бонус: мусорная концентрация Тилмикозин ВЛ 25 ──
    rec = by_id[913]
    if rec.get("concentration") == 25000.0:
        rec["concentration"] = 250.0
        changes.append("#913 Тилмикозин ВЛ 25: concentration 25000 мг/мл → 250 мг/мл (25%)")

    if not changes:
        print("already clean: изменений нет")
        return 0

    for line in changes:
        print(" *", line)
    print(f"\nитого правок: {len(changes)}")
    if args.check:
        print("check: файл не переписывался")
        return 1

    DB.write_text(json.dumps(db, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("файл переписан (round-trip формат сохранён)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
