def setf(obj: dict, key: str, value) -> bool:
    if obj.get(key) == value:
        return False
    obj[key] = value
    return True


def apply_branch(rec: dict, animal: str, fields: dict, changes: list, label: str) -> None:
    br = (rec.get("animal_specific") or {}).get(animal)
    if not isinstance(br, dict):
        return
    for key, value in fields.items():
        if setf(br, key, value):
            changes.append(f"{label}: {animal}.{key} → лейбл")


def revert_record(rec: dict, animals: list, freq: str, course: str, fixed: dict,
                  warn: str, wtext: str, wdays: int, branches: dict,
                  tag: str, changes: list) -> None:
    spec = rec.get("animal_specific") or {}
    junk = [a for a in spec if a not in branches]
    if junk:
        for a in junk:
            spec.pop(a)
        changes.append(f"{tag}: удалены вне-лейбловые ветки {junk}")
    if setf(rec, "animals", animals):
        changes.append(f"{tag}: animals → {animals}")
    if setf(rec, "frequency", freq):
        changes.append(f"{tag}: общая frequency → «{freq}»")
    if setf(rec, "method", "внутривыменно"):
        changes.append(f"{tag}: method → «внутривыменно» (был мусорный системный путь)")
    if setf(rec, "course_days", course):
        changes.append(f"{tag}: course_days → «{course}»")
    if setf(rec, "fixed_dose", fixed):
        changes.append(f"{tag}: fixed_dose → лейбл (по видам, шприц-туба 3 г)")
    if setf(rec, "withdrawal_days", wdays):
        changes.append(f"{tag}: withdrawal_days → {wdays}")
    if setf(rec, "withdrawal_text", wtext):
        changes.append(f"{tag}: withdrawal_text → лейбл-каренция")
    contra = rec.get("contraindications") or {}
    if setf(contra, "warnings", [warn]):
        changes.append(f"{tag}: противопоказания → лейбл")
    if setf(rec, "side_effects", SIDE):
        changes.append(f"{tag}: побочка → «как правило, не наблюдается»")
    rec["contraindications"] = contra
    for animal, fields in branches.items():
        apply_branch(rec, animal, fields, changes, tag)


