def apply_fix(drug: dict, fix: dict) -> bool:
    """Идемпотентно применяет правку к записи препарата."""
    changed = False
    for key, val in fix["drug"].items():
        if drug.get(key) != val:
            drug[key] = val
            changed = True
    new_as = fix["as"]
    old_as = drug.get("animal_specific")
    if old_as != new_as:
        drug["animal_specific"] = new_as
        changed = True
    return changed


def main() -> int:
    calc = load(CALC)
    verified = load(VERIFIED)
    changed_calc = []
    changed_verified = []

    for fix in FIXES:
        name = fix["name"]
        for drug in calc["drugs_calc"]:
            if drug.get("name") == name:
                if apply_fix(drug, fix):
                    changed_calc.append(name)
                break

        rec = verified.get(name)
        if rec is not None:
            if apply_fix(rec, fix):
                changed_verified.append(name)
        else:
            print(f"!! {name}: нет в verified_dosages — пропущено", file=sys.stderr)

    if changed_calc:
        dump(CALC, calc)
    if changed_verified:
        dump(VERIFIED, verified)

    print(f"drugs_calc.json: изменено {len(set(changed_calc))}/8")
    for n in dict.fromkeys(changed_calc):
        print("  *", n)
    print(f"verified_dosages.json: изменено {len(set(changed_verified))}/8")
    for n in dict.fromkeys(changed_verified):
        print("  *", n)
    if not changed_calc and not changed_verified:
        print("Изменений нет (идемпотентный повторный запуск).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
