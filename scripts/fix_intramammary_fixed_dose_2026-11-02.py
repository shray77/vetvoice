def apply(rec, spec):
    """Реверсия записи по лейблу. Возвращает список правок."""
    name = rec.get('name', '?')
    edits = []
    rid = rec['id']

    # 1. Числовая модель фиксированной дозы (верхний уровень).
    for key, val in (('dose_per_kg', 0), ('dose_min', 0.0), ('dose_max', 0.0),
                     ('dose_unit', 'fixed')):
        if rec.get(key) != val:
            edits.append(f'{key}: {rec.get(key)!r} → {val!r}')
            rec[key] = val

    # 2. Концентрация-мусор (мг на шприц, размеченные как мг/мл) → null.
    if spec['conc_null'] and rec.get('concentration') is not None:
        edits.append(f"concentration: {rec.get('concentration')!r} → null")
        rec['concentration'] = None

    # 3. Метод и фиксированная доза.
    if spec['fx'] is not None:
        if rec.get('fixed_dose') != spec['fx']:
            edits.append('fixed_dose: по лейблу')
            rec['fixed_dose'] = spec['fx']
    if spec.get('method') and rec.get('method') != spec['method']:
        edits.append(f"method: {rec.get('method')!r} → {spec['method']!r}")
        rec['method'] = spec['method']
    if spec['freq'] and rec.get('frequency') != spec['freq']:
        edits.append(f"frequency: {rec.get('frequency')!r} → {spec['freq']!r}")
        rec['frequency'] = spec['freq']
    if spec['course'] and rec.get('course_days') != spec['course']:
        edits.append(f"course_days: {rec.get('course_days')!r} → {spec['course']!r}")
        rec['course_days'] = spec['course']
    if spec['wd'] is not None and rec.get('withdrawal_days') != spec['wd']:
        edits.append(f"withdrawal_days: {rec.get('withdrawal_days')!r} → {spec['wd']!r}")
        rec['withdrawal_days'] = spec['wd']
    if spec['animals'] and rec.get('animals') != spec['animals']:
        edits.append(f"animals: {rec.get('animals')} → {spec['animals']}")
        rec['animals'] = spec['animals']

    # 4. Повидовые ветки: мусор мг/кг → модель фиксированной дозы.
    old = rec.get('animal_specific') or {}
    if spec['rebuild']:
        keep_freq = {k: v.get('frequency') for k, v in old.items()}
        keep_notes = {k: v.get('notes') for k, v in old.items()}
        new = {}
        for sp in (spec['animals'] or list(spec['fx'].keys())):
            b = branch(freq=spec['freq'], notes=spec.get('notes'),
                       course=spec['course'])
            if not spec['freq'] and keep_freq.get(sp):
                b['frequency'] = keep_freq[sp]
            if not spec.get('notes') and keep_notes.get(sp):
                b['notes'] = keep_notes[sp]
            new[sp] = b
        if old != new:
            removed = [k for k in old if k not in new]
            edits.append('animal_specific: rebuild '
                         f'({len(old)} → {len(new)} веток'
                         + (f', удалены: {removed}' if removed else '') + ')')
            rec['animal_specific'] = new
    else:
        for sp, b in old.items():
            junk = False
            for key in ('dose_per_kg', 'dose_min', 'dose_max'):
                if b.get(key):
                    b[key] = 0 if key == 'dose_per_kg' else 0.0
                    junk = True
            if b.get('dose_unit') != 'fixed':
                b['dose_unit'] = 'fixed'
                junk = True
            if spec.get('animals') and sp not in spec['animals']:
                continue  # ветка вне лейбла останется — удаляется ниже
            if b.get('route') != IM:
                b['route'] = IM
                junk = True
            if junk:
                edits.append(f'animal_specific[{sp}]: мг/кг-мусор → fixed')
        if spec.get('animals'):
            drop = [k for k in list(old) if k not in spec['animals']]
            for k in drop:
                del old[k]
                edits.append(f'animal_specific: удалена ветка {k} (вне лейбла)')

    # 5. Видимость в калькуляторе: с фиксированной дозой — да.
    want_calc = spec.get('calc', True)
    if rec.get('calculator_applicable') != want_calc:
        edits.append(f'calculator_applicable: '
                     f'{rec.get("calculator_applicable")} → {want_calc}')
        rec['calculator_applicable'] = want_calc

    # 6. Нечестный course_days (см. COURSE_DROP) — срез.
    if rid in COURSE_DROP and 'course_days' in rec:
        edits.append(f'course_days: {rec["course_days"]!r} → удалён '
                     '(противоречит верифицированной частоте)')
        del rec['course_days']

    return edits


