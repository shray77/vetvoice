import 'package:flutter/services.dart';

abstract final class AppHaptics {
  /// Нажатие «обычной» поверхности: плитки сетки, ряды меню, карточки,
  /// интерактивные чипы статуса.
  static void tap() => HapticFeedback.lightImpact();

  /// Выбор из вариантов: вкладки нижней навигации, ChoiceChip/FilterChip,
  /// подбор препарата, переключение темы.
  static void select() => HapticFeedback.selectionClick();

  /// Подтверждение значимого действия: убрать из избранного, применить
  /// протокол к калькулятору, включить/выключить wake word, выбрать дату.
  static void confirm() => HapticFeedback.mediumImpact();
}
